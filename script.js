    let currentStoryIndex = 0;

    const homePage = document.getElementById("homePage");
    const aboutPage = document.getElementById("aboutPage");
    const contactPage = document.getElementById("contactPage");
    const readingPage = document.getElementById("readingPage");
    const storyList = document.getElementById("storyList");
    const storyTitle = document.getElementById("storyTitle");
    const storyText = document.getElementById("storyText");
    const backButton = document.getElementById("backButton");

    const prevStoryBtn = document.getElementById("prevStoryBtn");
    const nextStoryBtn = document.getElementById("nextStoryBtn");

    const navHome = document.getElementById("navHome");
    const navAbout = document.getElementById("navAbout");
    const navContact = document.getElementById("navContact");
    const logoHome = document.getElementById("logoHome");

    const searchInput = document.getElementById("searchInput");
    const randomStoryBtn = document.getElementById("randomStoryBtn");
    const themeToggleBtn = document.getElementById("themeToggleBtn");
    const heroSection = document.querySelector(".hero");
    const heroDivider = document.querySelector(".golden-divider");

    function hideAllPages() {
      homePage.classList.add("hidden");
      aboutPage.classList.add("hidden");
      contactPage.classList.add("hidden");
      readingPage.classList.add("hidden");
      if (heroSection) heroSection.style.display = "none";
      if (heroDivider) heroDivider.style.display = "none";
    }

    function renderStories(storiesToDisplay) {
      storyList.innerHTML = "";
      
      if (storiesToDisplay.length === 0) {
        storyList.innerHTML = "<p style='grid-column: span 2; text-align: center; color: #806A5A;'>Aradığınız kriterlere uygun masal bulunamadı.</p>";
        return;
      }

      storiesToDisplay.forEach((story) => {
        const originalIndex = stories.findIndex(s => s.title === story.title);

        const card = document.createElement("div");
        card.className = "story-card";

        card.innerHTML = `
          <span class="story-number">MASAL ${originalIndex + 1}</span>
          <h3>${story.title}</h3>
          <p>${story.description}</p>
          <button class="read-button" data-index="${originalIndex}">
            Devamını Oku →
          </button>
        `;

        storyList.appendChild(card);
      });
    }

    function openStory(index) {
      currentStoryIndex = index;
      const selectedStory = stories[currentStoryIndex];

      storyTitle.textContent = selectedStory.title;
      storyText.innerHTML = selectedStory.text;

      // Önceki / Sonraki buton durumlarını güncelle
      prevStoryBtn.disabled = (currentStoryIndex === 0);
      nextStoryBtn.disabled = (currentStoryIndex === stories.length - 1);

      hideAllPages();
      readingPage.classList.remove("hidden");

      window.scrollTo({ top: 0, behavior: "smooth" });
    }

    renderStories(stories);

    storyList.addEventListener("click", function(event) {
      const button = event.target.closest(".read-button");
      if (!button) return;

      openStory(parseInt(button.dataset.index));
    });

    prevStoryBtn.addEventListener("click", function() {
      if (currentStoryIndex > 0) {
        openStory(currentStoryIndex - 1);
      }
    });

    nextStoryBtn.addEventListener("click", function() {
      if (currentStoryIndex < stories.length - 1) {
        openStory(currentStoryIndex + 1);
      }
    });

    function showHome() {
      hideAllPages();
      homePage.classList.remove("hidden");
      if (heroSection) heroSection.style.display = "block";
      if (heroDivider) heroDivider.style.display = "flex";
      navHome.classList.add("active");
      navAbout.classList.remove("active");
      navContact.classList.remove("active");
      window.scrollTo({ top: 0, behavior: "smooth" });
    }

    navHome.addEventListener("click", (e) => { e.preventDefault(); showHome(); });
    logoHome.addEventListener("click", () => { showHome(); });

    navAbout.addEventListener("click", (e) => {
      e.preventDefault();
      hideAllPages();
      aboutPage.classList.remove("hidden");
      navAbout.classList.add("active");
      navHome.classList.remove("active");
      navContact.classList.remove("active");
      window.scrollTo({ top: 0, behavior: "smooth" });
    });

    navContact.addEventListener("click", (e) => {
      e.preventDefault();
      hideAllPages();
      contactPage.classList.remove("hidden");
      navContact.classList.add("active");
      navHome.classList.remove("active");
      navAbout.classList.remove("active");
      window.scrollTo({ top: 0, behavior: "smooth" });
    });

    backButton.addEventListener("click", function() {
      showHome();
    });

    searchInput.addEventListener("input", function(e) {
      const term = e.target.value.toLowerCase().trim();
      const filtered = stories.filter(s => 
        s.title.toLowerCase().includes(term) || s.description.toLowerCase().includes(term)
      );
      showHome();
      renderStories(filtered);
    });

    randomStoryBtn.addEventListener("click", function() {
      const randomIndex = Math.floor(Math.random() * stories.length);
      openStory(randomIndex);
    });

    themeToggleBtn.addEventListener("click", function() {
      document.body.classList.toggle("dark-mode");
      if (document.body.classList.contains("dark-mode")) {
        themeToggleBtn.textContent = "☀️";
      } else {
        themeToggleBtn.textContent = "🌙";
      }
    });